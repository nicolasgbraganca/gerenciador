-- O app usa esta função para criar a venda e retirar o produto do catálogo
-- dentro da mesma transação do Postgres.
create or replace function public.registrar_venda(p_produto_id uuid, p_preco_venda numeric)
returns public.vendas
language plpgsql
security invoker
set search_path = public
as $$
declare
  produto public.produtos%rowtype;
  venda public.vendas%rowtype;
begin
  if auth.uid() is null then raise exception 'Autenticação necessária'; end if;
  if p_preco_venda is null or p_preco_venda <= 0 then raise exception 'Preço inválido'; end if;

  select * into produto from public.produtos where id = p_produto_id for update;
  if not found or produto.vendido then raise exception 'Produto indisponível'; end if;

  insert into public.vendas (produto_id, nome_produto, custo, preco_sugerido, preco_venda, lucro)
  values (produto.id, produto.nome, produto.custo, produto.preco,
          p_preco_venda, p_preco_venda - produto.custo)
  returning * into venda;

  update public.produtos set vendido = true where id = produto.id;
  return venda;
end;
$$;

revoke all on function public.registrar_venda(uuid, numeric) from public, anon;
grant execute on function public.registrar_venda(uuid, numeric) to authenticated;

create or replace function public.anular_venda(p_venda_id uuid)
returns void language plpgsql security invoker set search_path = public as $$
declare venda public.vendas%rowtype;
begin
  if auth.uid() is null then raise exception 'Autenticação necessária'; end if;
  select * into venda from public.vendas where id = p_venda_id for update;
  if not found or venda.anulada then raise exception 'Venda não encontrada ou já anulada'; end if;
  update public.vendas set anulada = true where id = p_venda_id;
  update public.produtos set vendido = false where id = venda.produto_id;
end;
$$;
revoke all on function public.anular_venda(uuid) from public, anon;
grant execute on function public.anular_venda(uuid) to authenticated;

