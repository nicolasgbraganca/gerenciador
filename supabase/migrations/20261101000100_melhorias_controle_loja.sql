-- Premissas conferidas no cliente: produtos (id UUID, nome, custo, preco, fotos, vendido),
-- vendas (produto_id, nome_produto, custo, preco_sugerido, preco_venda, lucro, vendido_em),
-- propostas. Revise os tipos/nomes do schema remoto antes de aplicar.

create table if not exists public.despesas (
  id bigint generated by default as identity primary key,
  descricao text not null,
  valor numeric(12,2) not null check (valor > 0),
  data date not null default current_date,
  criado_em timestamptz not null default now()
);

create table if not exists public.configuracoes_loja (
  id integer primary key check (id = 1),
  name text not null default 'Pereira & Alem',
  phone text not null default '',
  email text not null default '',
  atualizado_em timestamptz not null default now()
);

alter table public.vendas add column if not exists anulada boolean not null default false;

insert into public.configuracoes_loja (id) values (1) on conflict (id) do nothing;

alter table public.despesas enable row level security;
alter table public.configuracoes_loja enable row level security;

-- Replace permissive policies on the application's core tables. In a single-owner
-- deployment, authenticated means the owner's Supabase account (disable signups).
do $$
declare p record;
begin
  for p in select schemaname, tablename, policyname from pg_policies
    where schemaname = 'public' and tablename in ('produtos','vendas','propostas')
  loop
    execute format('drop policy %I on %I.%I', p.policyname, p.schemaname, p.tablename);
  end loop;
end $$;

alter table public.produtos enable row level security;
alter table public.vendas enable row level security;
alter table public.propostas enable row level security;

revoke all on public.produtos from public, anon;
revoke all on public.vendas from public, anon;
revoke all on public.propostas from public, anon;
grant select (id, nome, preco, descricao, fotos, vendido, criado_em) on public.produtos to anon;
grant insert (produto_id, nome, telefone, email, tipo, mensagem, desc_venda, valor_venda, foto_venda) on public.propostas to anon;
grant select, insert, update, delete on public.produtos to authenticated;
grant select on public.vendas to authenticated;
grant select on public.propostas to authenticated;
grant insert on public.vendas to authenticated;
do $$
declare seq text;
begin
  seq := pg_get_serial_sequence('public.propostas', 'id');
  if seq is not null then execute format('grant usage, select on sequence %s to anon', seq::regclass); end if;
  seq := pg_get_serial_sequence('public.vendas', 'id');
  if seq is not null then execute format('grant usage, select on sequence %s to authenticated', seq::regclass); end if;
end $$;

